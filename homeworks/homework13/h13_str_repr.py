# Опишите коротким комментарием, чем они отличаются и какой из них обычно переопределяют в Django-моделях.
# (Опционально, для тех, кто быстро справился, — посмотрите, что даёт @dataclass для такого класса,
# и оставьте вывод в комментарии.)

# Оба отвечают за строковое представление объекта, но используются для разных целей
# __str__() предназначен для удобного отображения объекта пользователю,
# а __repr__() — для более подробного представления, полезного при отладке.
# В Django-моделях обычно переопределяют __str__, чтобы объекты имели понятные названия в админке.

# Декоратор @dataclass автоматически создает __init__() и __repr__(), поэтому код становится короче.


@dataclass
class Book:
    title: str
    author: str
    year: int

    def __str__(self):
        return f"«{self.title}» — {self.author}"


book = Book(title="Война и мир", author="Лев Толстой", year=1869)

print(book)
print(repr(book))
