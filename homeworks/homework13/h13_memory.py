import sys


# Звёздочка. Сравните стоимость «экземпляра» и «класса» на практике.
# Создайте класс Point с __init__(self, x, y). Затем: сравните по памяти и по доступу,
# сколько занимает объект (import sys; sys.getsizeof(Point(1, 2))) и сколько — сам класс
# (sys.getsizeof(Point)). Выведите разницу и ответьте комментарием: почему объект «тяжелее»,
# и что это значит для создания тысяч записей (например, в Django при работе с большим queryset).
# Подсказка: загляните в __dict__ экземпляра (p.__dict__).


class Point:
    def __init__(self, x: int, y: int) -> None:
        self.x = x
        self.y = y


p = Point(1, 2)

# Размер экземпляра
object_size = sys.getsizeof(p)

# Размер класса
class_size = sys.getsizeof(Point)

# Размер словаря экземпляра
dict_size = sys.getsizeof(p.__dict__)

print(f"Размер экземпляра: {object_size} байт")
print(f"Размер класса: {class_size} байт")
print(f"Размер __dict__: {dict_size} байт")
print(f"Размер экземпляра и его словаря: {object_size + dict_size} байт")
print(f"Размер 1000 экземпляров со словарями: {(object_size + dict_size)*1000} байт")

