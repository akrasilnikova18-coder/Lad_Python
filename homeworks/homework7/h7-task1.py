#Факты о себе как кортеж. Создать кортеж person из имени, возраста и города.
#Вывести его тип, длину, элемент по индексу и срез. Отдельно продемонстрировать,
#почему (5) — не кортеж, а (5,) — кортеж. Попробовать изменить элемент и перехватить TypeError.

person = ("Алена", 42, "Нижний Новгород")

print(type(person)) #тип кортежа
print(len(person)) #длина кортежа
print(person[1]) #элемент по индексу
print(person[1:]) #срез со второго элемента до конца

single = (5,) #кортеж из одного элемента, потому что на конце запятая
print(type(single))

not_tuple = (5) #не кортеж, а число, потому что нет запятой и 1 элемент
print(type(not_tuple))

try:
    person[1] = 35
except TypeError as error:
    print(f"Нельзя изменить элемент кортежа: {error}")
