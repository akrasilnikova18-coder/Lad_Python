def create_post(title: str, author: str, text: str) -> dict:
    """Добавляет новую статью в список статей и возвращает ее"""
    article = {
        "title": title,
        "author": author,
        "text": text,
    }

    articles.append(article)
    return article


def list_posts() -> list[dict]:
    """Возвращает все статьи"""
    return articles


def find_post(title: str) -> dict | None:
    """Ищет статьи по названию и возвращает статьи с таким названием, если статья есть,
    или None, если статьи нет"""
    for article in articles:
        if article["title"] == title:
            return article
    return None

